def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)

    schematic_path = OUT / "openrd_pdb_v0_1_schematic.json"
    pcb_path = OUT / "openrd_pdb_v0_1_pcb.json"
    bom_path = OUT / "openrd_pdb_v0_1_bom.csv"
    zip_path = OUT / "openrd_pdb_v0_1_easyeda_std.zip"

    schematic_path.write_text(json.dumps(build_schematic(), ensure_ascii=False, indent=2), encoding="utf-8")
    pcb_path.write_text(json.dumps(build_pcb(), ensure_ascii=False, indent=2), encoding="utf-8")

    with bom_path.open("w", encoding="utf-8", newline="") as fp:
        writer = csv.writer(fp)
        writer.writerows(BOM)

    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.write(schematic_path, schematic_path.name)
        zf.write(pcb_path, pcb_path.name)
        zf.write(bom_path, bom_path.name)

    print(f"wrote {schematic_path}")
    print(f"wrote {pcb_path}")
    print(f"wrote {bom_path}")
    print(f"wrote {zip_path}")


if __name__ == "__main__":
    main()
