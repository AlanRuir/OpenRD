        (530, 120, 120, 50, "J2 MOTOR_OUT"),
        (530, 230, 100, 50, "F2 RK"),
        (690, 230, 130, 50, "J3 DCDC_IN"),
        (850, 210, 150, 90, "U1 LTC3780"),
        (1060, 230, 130, 50, "J4 DCDC_OUT"),
        (1230, 230, 120, 50, "J5 RK_OUT"),
