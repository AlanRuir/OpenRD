        ("BATT_SENSE", 735, 380),
        ("GND common on all negative pins", 80, 520),
        ("Battery charge port DC5521 stays on battery pack. DO NOT CHARGE HERE.", 80, 550),
        ("DC5525 output to RK3588 is center positive.", 80, 580),
